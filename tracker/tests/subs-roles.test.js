const NAMES = 'aliceblue antiquewhite aqua aquamarine azure beige bisque black blanchedalmond blue blueviolet brown burlywood cadetblue chartreuse chocolate coral cornflowerblue cornsilk crimson cyan darkblue darkcyan darkgoldenrod darkgray darkgreen darkgrey darkkhaki darkmagenta darkolivegreen darkorange darkorchid darkred darksalmon darkseagreen darkslateblue darkslategray darkslategrey darkturquoise darkviolet deeppink deepskyblue dimgray dimgrey dodgerblue firebrick floralwhite forestgreen fuchsia gainsboro ghostwhite gold goldenrod gray green greenyellow grey honeydew hotpink indianred indigo ivory khaki lavender lavenderblush lawngreen lemonchiffon lightblue lightcoral lightcyan lightgoldenrodyellow lightgray lightgreen lightgrey lightpink lightsalmon lightseagreen lightskyblue lightslategray lightslategrey lightsteelblue lightyellow lime limegreen linen magenta maroon mediumaquamarine mediumblue mediumorchid mediumpurple mediumseagreen mediumslateblue mediumspringgreen mediumturquoise mediumvioletred midnightblue mintcream mistyrose moccasin navajowhite navy oldlace olive olivedrab orange orangered orchid palegoldenrod palegreen paleturquoise palevioletred papayawhip peachpuff peru pink plum powderblue purple rebeccapurple red rosybrown royalblue saddlebrown salmon sandybrown seagreen seashell sienna silver skyblue slateblue slategray slategrey snow springgreen steelblue tan teal thistle tomato turquoise violet wheat white whitesmoke yellow yellowgreen'.split(' ');
const nameRe = new RegExp('(^|[^\\w-])(' + NAMES.join('|') + ')(?![\\w-])', 'i');
const fnRe = /(^|[^\w-])(rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(/i;
const hexRe = /#[0-9a-f]{3,8}\b/i;
const TOKEN_RULES = new Set([':root', ':root:not([data-theme="light"])', ':root[data-theme="dark"]', '.subs-page', '.map-panel', ':root:not([data-theme="light"]) .map-panel', ':root[data-theme="dark"] .map-panel']);
const MIX_OK = /^color-mix\(in (srgb|oklab), var\(\) [\d.]+%, transparent\)$/; // after bare(): the token name is removed
// the colour-bearing parts of a value: strings and var() names removed
const bare = (v) => v.replace(/"[^"]*"|'[^']*'/g, '').replace(/var\(\s*--[a-z0-9-]+/gi, 'var(');
function mixes(v) { // the color-mix( ... ) expressions of a value, balanced
  const out = []; let i = v.indexOf('color-mix(');
  while (i >= 0) { let d = 0, j = i + 9; for (; j < v.length; j++) { if (v[j] === '(') d++; else if (v[j] === ')') { d--; if (d === 0) break; } } out.push(v.slice(i, j + 1)); i = v.indexOf('color-mix(', j); }
  return out;
}
function lintCss() {
  const found = [];
  for (const r of rules) {
    const tokenRule = TOKEN_RULES.has(r.sel);
    for (const d of r.body.split(';')) {
      const k = d.indexOf(':'); if (k < 0) continue;
      const prop = d.slice(0, k).trim(), val = d.slice(k + 1).trim();
      if (tokenRule && prop.startsWith('--')) continue; // a custom-property declaration inside a token rule may hold any colour
      if (T.LINT_PENDING.includes(prop)) continue;
      const v = bare(val);
      const ms = mixes(v);
      for (const m of ms) if (!MIX_OK.test(m)) found.push(r.sel.slice(0, 70) + ' { ' + prop + ': ' + m.slice(0, 80));
      const rest = ms.reduce((s, m) => s.replace(m, ''), v);
      if (hexRe.test(rest) || fnRe.test(rest) || nameRe.test(rest.replace(/transparent|currentcolor/gi, ''))) found.push(r.sel.slice(0, 70) + ' { ' + prop + ': ' + val.slice(0, 80));
    }
  }
  return found;
}

test('lint: subs.css holds no raw colour outside the token definitions', () => {
  assert.deepEqual(lintCss(), [], 'raw colours in ordinary rules (the exceptions live in LINT_PENDING in tools/subs-roles.js)');
  assert.deepEqual(T.LINT_PENDING, [], 'W33 retired --ringc, the last exception; the list is empty');
  // the lint itself catches what it should
  const probe = ['color: #fff', 'background: rgba(0, 0, 0, .6)', 'color: oklch(0.7 0.1 20)', 'border: 1px solid red', 'background: color-mix(in srgb, var(--ink) 50%, var(--paper))', 'color: white'];
  for (const p of probe) { const [prop, val] = p.split(/:\s(.*)/s), v = bare(val), ms = mixes(v), rest = ms.reduce((s, m) => s.replace(m, ''), v); assert.ok(ms.some((m) => !MIX_OK.test(m)) || hexRe.test(rest) || fnRe.test(rest) || nameRe.test(rest), p); }
  for (const p of ['color: var(--ink)', 'background: transparent', 'color: currentColor', 'background: color-mix(in srgb, var(--chart-ink) 4%, transparent)', 'white-space: nowrap']) { const [prop, val] = p.split(/:\s(.*)/s), v = bare(val), ms = mixes(v), rest = ms.reduce((s, m) => s.replace(m, ''), v).replace(/transparent|currentcolor/gi, ''); assert.ok(ms.every((m) => MIX_OK.test(m)) && !hexRe.test(rest) && !fnRe.test(rest) && !nameRe.test(rest), p); }
});

test('lint: chart.js and subs.js hold no colour literal and no fill or stroke value other than none and currentColor', () => {
  for (const [name, text] of [['chart.js', chartJs], ['subs.js', subsJs]]) {
    const noEntity = text.replace(/&#\d+;|&#x[0-9a-f]+;/gi, '');
    assert.ok(!/(^|[^\w&])#[0-9a-f]{6}\b|(^|[^\w&])#[0-9a-f]{3}\b(?![\w-])/i.test(noEntity.replace(/href="#[^"]*"|'#[\w-]*'|"#[\w-]*"/g, '')), name + ' holds a hex colour');
    assert.ok(!/\b(rgba?|hsla?|hwb|oklab|oklch|lch)\(/i.test(text), name + ' holds a colour function');
    for (const m of text.matchAll(/\b(fill|stroke)=\\?["']([^"'\\]*)/g)) assert.ok(['none', 'currentColor'].includes(m[2]) || /^'? ?\+/.test(m[2]) || m[2] === '', name + ' has ' + m[1] + '="' + m[2] + '"');
  }
});
