'use strict';
// Submersibles colour roles (docs/submersibles-look-spec.md, Revision 4, Rev4.4 to Rev4.6, W31).
// The generated document equals the tool's output; 27 roles and 102 tones; every colour token the rules use belongs to a
// role or is a pointer; every role token is used or explained; every rule that uses a colour matches a zone that allows the
// token's role; gil is in no zone of the Map; and the lint: no raw colour outside the token rules.
// Run: node --test tests/subs-roles.test.js
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const T = require('../tools/subs-roles.js');
const P = require('./subs-palette.js');

const SRC = path.join(P.CC, 'src', 'submersibles');
const css = P.css, subsJs = fs.readFileSync(path.join(SRC, 'subs.js'), 'utf8'), chartJs = fs.readFileSync(path.join(SRC, 'chart.js'), 'utf8');
const rules = T.cssRules(css);

test('the committed document is what the tool writes (no date, no machine text)', () => {
  const have = fs.readFileSync(T.DOC, 'utf8');
  assert.equal(have, T.build(), 'docs/submersibles-colour-roles.md differs from tracker/tools/subs-roles.js output; run: node tracker/tools/subs-roles.js');
  assert.equal(T.build(), T.build(), 'two runs give the same text');
  assert.ok(have.startsWith('# Submersibles: colour roles\n\nGenerated by tracker/tools/subs-roles.js. Do not edit.'));
  assert.ok(!/\b20\d\d-\d\d-\d\d\b/.test(have), 'no date');
  assert.ok(!/\/home\/|\/tmp\/|C:\\/.test(have), 'no machine path');
  // 21 themes in light and dark for every role and the shared tone: 42 rows each
  const rows = have.split('\n').filter((l) => /^\| [A-Z][^|]* \| (light|dark) \|/.test(l)).length;
  assert.equal(rows, 42 * (T.ROLES.length + 1));
});

test('27 roles and 102 tones (25 theme tones in 9 roles, 77 meaning tones in 18 roles)', () => {
  const c = T.counts();
  assert.deepEqual(c, { roles: 27, tones: 102, themeRoles: 9, themeTones: 25, meaningRoles: 18, meaningTones: 77 });
  const all = T.ROLES.concat([T.SHARED]).flatMap((r) => r.tokens.map((t) => t[0]));
  assert.equal(new Set(all).size, all.length, 'every token is named once');
});

// the colour tokens that subs.css, subs.js and chart.js use
const used = new Map(); // token -> where
for (const [name, text] of [['subs.css', css], ['subs.js', subsJs], ['chart.js', chartJs]]) for (const m of text.matchAll(/var\((--[a-z0-9-]+)/g)) if (!used.has(m[1])) used.set(m[1], name);

test('every colour token the rules use is in a role, an alias or the retiring list', () => {
  const unknown = [...used.keys()].filter((t) => !T.NON_COLOUR.has(t) && !T.roleOf[t] && !T.ALIASES[t] && !T.RETIRING[t]);
  assert.deepEqual(unknown, [], 'tokens in no role');
  // a token only declared is in a role too (a declaration the rules never read is reported below)
  const declared = [...css.matchAll(/(?:^|[\s{;])(--[a-z0-9-]+)\s*:/g)].map((m) => m[1]).filter((t) => !T.NON_COLOUR.has(t));
  assert.deepEqual([...new Set(declared)].filter((t) => !T.roleOf[t] && !T.ALIASES[t] && !T.RETIRING[t]), [], 'declared tokens in no role');
});

test('every token of a role is used by a rule, or listed in UNUSED with a reason that still holds', () => {
  const tokens = T.ROLES.concat([T.SHARED]).flatMap((r) => r.tokens.map((t) => t[0]));
  // a token is also used when another token's definition reads it (the sea and screen aliases read the sea tones)
  const unused = tokens.filter((t) => !used.has(t));
  assert.deepEqual(unused.sort(), Object.keys(T.UNUSED).sort(), 'the unused tokens are exactly the ones listed in UNUSED');
  for (const [t, why] of Object.entries(T.UNUSED)) assert.ok(why.length > 10 && tokens.includes(t), t + ' needs a reason and a role');
});

test('every rule that uses a colour token matches a zone whose roles include that token\'s role', () => {
  const bad = [], unmatched = [], seen = new Set();
  for (const r of rules) {
    const toks = T.usedTokens(r.body).filter((t) => !T.NON_COLOUR.has(t));
    if (!toks.length) continue;
    const z = T.zoneOf(r.sel);
    if (!z) { unmatched.push(r.sel.slice(0, 110)); continue; }
    seen.add(z);
    if (z.roles[0] === '*') continue;
    for (const t of toks) {
      const roles = T.rolesOf(t);
      if (!roles) { bad.push(r.sel.slice(0, 80) + ' uses ' + t + ' (in no role)'); continue; }
      if (!roles.some((x) => z.roles.includes(x))) bad.push(r.sel.slice(0, 80) + ' [' + z.screen + ': ' + z.zone.slice(0, 40) + '] uses ' + t + ' (' + roles.join('/') + ')');
    }
  }
  assert.deepEqual(unmatched, [], unmatched.length + ' rules match no zone');
  assert.deepEqual(bad, [], bad.length + ' colour uses outside their zone\'s roles');
  // every zone fragment finds at least one rule or is the zone of a rule: a stale fragment is reported
  const stale = [];
  T.ZONES.forEach((z) => z.frags.forEach((f) => { const exact = f.startsWith('='), frag = exact ? f.slice(1) : f; if (!rules.some((r) => (exact ? r.sel === frag : r.sel.includes(frag)))) stale.push(z.screen + ': ' + f); }));
  assert.deepEqual(stale, [], 'zone fragments that match no rule in subs.css');
});

test('gil is in no zone of the Map', () => {
  for (const z of T.ZONES.filter((x) => x.screen === 'Map')) assert.ok(!z.roles.includes('gil') && !z.roles.includes('*'), z.zone);
  for (const r of rules) {
    const z = T.zoneOf(r.sel);
    if (z && z.screen === 'Map') assert.ok(!T.usedTokens(r.body).some((t) => /^--gil-/.test(t)), r.sel + ' uses gil inside the Map');
  }
});

