'use strict';
// Lists colour roles and look rules (docs/lists-look-spec.md, decision L7 and the kit of section 3; docs/design-rules.md sections 7 and 6).
// The generated document equals the tool's output; fifteen roles and 43 tones; every colour token the rules use belongs to a role or is a pointer; every role
// token is read by a rule or explained; the six meaning roles keep one hue each; in all 21 themes, light and dark, text reads at 4.5:1 on its field and on the page,
// graphics at 3:1, ink on a wash at 7:1; no rule outside the token block holds a colour; monospace is for figures only; every role is drawn with a word; the phone
// keeps 40 px tap targets. It replaces tests/lists-look.test.js (the six-role fill and ink pair of work item W11).
// Run: node tests/lists-roles.test.js
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const T = require('../tools/lists-roles.js');
const P = require('./subs-palette.js');
const { THEMES, ratio, linear, rgbToLch, hueGap } = P;

const SRC = path.join(P.CC, 'src', 'lists');
const css = fs.readFileSync(path.join(SRC, 'lists.css'), 'utf8'), js = fs.readFileSync(path.join(SRC, 'lists.js'), 'utf8'), html = fs.readFileSync(path.join(SRC, 'index.html'), 'utf8');
const body = css.replace(/\/\*[\s\S]*?\*\//g, '');
const rules = T.cssRules(css);
const B = T.tokenBlocks();
const SIX = T.SIX;

test('the committed document is what the tool writes (no date, no machine text)', () => {
  const have = fs.readFileSync(T.DOC, 'utf8');
  assert.equal(have, T.build(), 'docs/lists-colour-roles.md differs from tracker/tools/lists-roles.js output; run: node tracker/tools/lists-roles.js');
  assert.equal(T.build(), T.build(), 'two runs give the same text');
  assert.ok(have.startsWith('# Lists: colour roles\n\nGenerated by tracker/tools/lists-roles.js. Do not edit.'));
  assert.ok(!/\b20\d\d-\d\d-\d\d\b/.test(have), 'no date');
  assert.ok(!/\/home\/|\/tmp\/|C:\\/.test(have), 'no machine path');
  // 21 themes in light and dark for every role and the shared tone: 42 rows each
  const rows = have.split('\n').filter((l) => /^\| [A-Z][^|]* \| (light|dark) \|/.test(l)).length;
  assert.equal(rows, 42 * (T.ROLES.length + 1));
});

test('15 roles and 43 tones (8 theme roles; the six meaning roles with four tones each; the shared text tone)', () => {
  assert.equal(T.ROLES.length + 1, 15);
  const all = T.ROLES.concat([T.SHARED]).flatMap((r) => r.tokens.map((t) => t[0]));
  assert.equal(all.length, 43);
  assert.equal(new Set(all).size, all.length, 'every token is named once');
  assert.deepEqual(T.ROLES.filter((r) => r.kind === 'meaning').map((r) => r.id), SIX);
  for (const r of T.ROLES.filter((x) => x.kind === 'meaning')) assert.deepEqual(r.tokens.map((t) => t[1]), ['field', 'graphic', 'text', 'wash'], r.id);
});

test('the token block holds the six roles in both modes: a field, a graphic, a text tone and a wash; the dark sets match', () => {
  const want = SIX.flatMap((r) => ['fill', 'edge', 'ink', 'wash'].map((k) => '--lr-' + r + '-' + k));
  for (const t of want) assert.ok(t in B.light, t + ' is declared in :root');
  assert.deepEqual(B.media, B.dark, 'with no theme chosen yet and a dark system, the fallback is the dark set');
  assert.deepEqual(Object.keys(B.dark), ['--on-mid'], 'only the text on a field changes with the mode');
  assert.equal(B.light['--on-mid'], 'var(--ink)'); assert.equal(B.dark['--on-mid'], 'var(--paper)');
  for (const r of SIX) assert.match(B.light['--lr-' + r + '-fill'], /^oklch\(\s*[\d.]+\s+[\d.]+\s+[\d.]+\s*\)$/, r + ' field is one oklch colour');
});

// every colour token the rules use, outside the token block
const used = new Set();
for (const r of rules) { if (T.TOKEN_RULES.includes(r.sel)) continue; for (const t of T.usedTokens(r.body)) used.add(t); }
const theme = new Set(['--paper', '--paper-2', '--paper-3', '--slip', '--ink', '--ink-2', '--ink-3', '--rule', '--grid', '--slab', '--on-slab', '--on-slab-2', '--seal', '--on-seal', '--hi', '--molten', '--shadow', '--scrim', '--on-mid', '--ochre', '--lb-a', '--lb-b', '--lb-c']);
const NOT_COLOUR = new Set(['--jm', '--edge', '--f-disp', '--f-kick', '--f-body', '--f-data', '--f-serif', '--r']);

test('every colour token the rules use is in a role, a pointer, a theme token or a size/face', () => {
  const unknown = [...used].filter((t) => !T.roleOf[t] && !T.POINTERS[t] && !theme.has(t) && !NOT_COLOUR.has(t));
  assert.deepEqual(unknown, [], 'tokens in no role');
});

test('every token of a role is read by a rule or by another token, or is listed in UNUSED with a reason that still holds', () => {
  const all = T.ROLES.concat([T.SHARED]).flatMap((r) => r.tokens.map((t) => t[0]));
  const unused = all.filter((t) => !new RegExp('var\\(' + t + '[,)]').test(body)); // a token is used when any rule, or another token, reads it
  assert.deepEqual(unused.sort(), Object.keys(T.UNUSED).sort(), 'the unused tokens are exactly the ones listed in UNUSED');
  for (const [t, why] of Object.entries(T.UNUSED)) assert.ok(why.length > 10 && all.includes(t), t + ' needs a reason and a role');
});

test('the pointers (--f, --g, --s, --w, --on-f, --rf, --rt) are set only to a token of a role they may point at', () => {
  const bad = [];
  for (const r of rules) {
    if (T.TOKEN_RULES.includes(r.sel)) continue;
    for (const [k, v] of Object.entries(T.decls(r.body))) {
      if (!T.POINTERS[k]) continue;
      const m = /^var\((--[\w-]+)\)$/.exec(v); if (!m) { bad.push(r.sel + ' ' + k + ': ' + v); continue; }
      const id = T.roleOf[m[1]]; if (!id) { bad.push(r.sel + ' ' + k + ': ' + v + ' (no role)'); continue; }
      const kind = SIX.includes(id) ? 'meaning' : id; if (!T.POINTERS[k].includes(kind)) bad.push(r.sel + ' ' + k + ': ' + v + ' (' + id + ')');
    }
  }
  assert.deepEqual(bad, []);
});

const rgbOf = (mode, tok) => T.rgbOf(tok, T.envOf(THEMES[0], mode));
test('every field lies inside sRGB, and the six fields are at least 30 degrees apart in hue in every theme', () => {
  for (const row of THEMES) for (const mode of ['light', 'dark']) {
    const ctx = T.envOf(row, mode);
    for (const r of SIX) for (const k of ['fill', 'edge', 'ink']) assert.ok(linear(T.rgbOf('--lr-' + r + '-' + k, ctx)).every((v) => v >= -0.002 && v <= 1.002), row[1] + ' ' + mode + ' ' + r + ' ' + k);
    for (const [k, floor] of [['fill', T.FLOORS.hueGap], ['edge', T.FLOORS.hueGap], ['ink', T.FLOORS.hueGapText]]) {
      const hs = SIX.map((r) => rgbToLch(T.rgbOf('--lr-' + r + '-' + k, ctx))[2]);
      for (let a = 0; a < hs.length; a++) for (let b = a + 1; b < hs.length; b++) assert.ok(hueGap(hs[a], hs[b]) >= floor, row[1] + ' ' + mode + ' ' + k + ' ' + SIX[a] + '/' + SIX[b] + ' ' + hueGap(hs[a], hs[b]).toFixed(1));
    }
    for (const r of SIX) { const f = rgbToLch(T.rgbOf('--lr-' + r + '-fill', ctx))[2]; for (const k of ['edge', 'ink']) assert.ok(hueGap(f, rgbToLch(T.rgbOf('--lr-' + r + '-' + k, ctx))[2]) <= T.FLOORS.hueDrift, row[1] + ' ' + mode + ' ' + r + ' ' + k + ' keeps its role\'s hue'); }
  }
});

test('in all 21 themes, light and dark: contrast floors of design rule K5', () => {
  assert.equal(THEMES.length, 21);
  const F = T.FLOORS, low = [];
  for (const row of THEMES) for (const mode of ['light', 'dark']) {
    const ctx = T.envOf(row, mode), e = ctx.env, where = row[1] + ' ' + mode;
    for (const r of SIX) {
      const f = T.rgbOf('--lr-' + r + '-fill', ctx), g = T.rgbOf('--lr-' + r + '-edge', ctx), s = T.rgbOf('--lr-' + r + '-ink', ctx), w = T.rgbOf('--lr-' + r + '-wash', ctx), om = T.rgbOf('--on-mid', ctx);
      if (ratio(om, f) < F.onField) low.push(where + ' ' + r + ' text on its field ' + ratio(om, f).toFixed(2));
      if (ratio(e['--ink'], w) < F.inkOnWash) low.push(where + ' ' + r + ' ink on its wash ' + ratio(e['--ink'], w).toFixed(2));
      for (const b of ['--paper', '--paper-2', '--slip']) {
        if (ratio(s, e[b]) < F.textOnPage) low.push(where + ' ' + r + ' text tone on ' + b + ' ' + ratio(s, e[b]).toFixed(2));
        if (ratio(g, e[b]) < F.graphicOnPage) low.push(where + ' ' + r + ' graphic tone on ' + b + ' ' + ratio(g, e[b]).toFixed(2));
      }
    }
    if (ratio(e['--paper'], e['--ink']) < F.onSlab) low.push(where + ' slab text ' + ratio(e['--paper'], e['--ink']).toFixed(2));
    if (ratio(e['--paper-3'], e['--ink']) < F.onSlab2) low.push(where + ' slab second text ' + ratio(e['--paper-3'], e['--ink']).toFixed(2));
    // the text on the accent is chosen by measured contrast (look.js onSeal)
    const onSeal = e['--on-seal']; if (ratio(onSeal, e['--seal']) < 4.5) low.push(where + ' text on the accent ' + ratio(onSeal, e['--seal']).toFixed(2));
  }
  assert.deepEqual(low, []);
  const m = T.measure();
  console.log('lists roles: lowest text on field ' + Math.min(...SIX.map((r) => m[r + ' on-mid on fill'].v)).toFixed(2) + ', lowest text tone on page or panel ' + Math.min(...SIX.map((r) => m[r + ' text tone on page, panel'].v)).toFixed(2) + ', lowest graphic tone ' + Math.min(...SIX.map((r) => m[r + ' graphic tone on page, panel'].v)).toFixed(2) + ' (21 themes x 2 modes x 6 roles)');
});

const NAMES = 'black white red blue green yellow orange purple pink gray grey gold navy teal tan silver maroon olive lime aqua fuchsia brown crimson coral salmon tomato khaki ivory beige indigo violet magenta cyan'.split(' ');
const rawColour = (val) => { // a colour written out in a value: strings and var() names do not count
  const bare = val.replace(/"[^"]*"|'[^']*'/g, '').replace(/var\(\s*--[\w-]+/g, 'var(');
  return /#[0-9a-f]{3,8}\b/i.test(bare) || /\b(rgba?|hsla?|hwb|lab|lch|oklab|oklch|color|color-mix)\(/i.test(bare) || new RegExp('(^|[^\\w-])(' + NAMES.join('|') + ')(?![\\w-])', 'i').test(bare);
};
test('no rule outside the token block holds a colour: only var() of a theme token or a role token', () => {
  const bad = [];
  for (const r of rules) {
    if (T.TOKEN_RULES.includes(r.sel)) continue;
    for (const d of r.body.split(/;(?![^(]*\))/)) {
      const k = d.indexOf(':'); if (k < 0) continue;
      const prop = d.slice(0, k).trim(), val = d.slice(k + 1).trim();
      if (rawColour(val)) bad.push(r.sel + ' { ' + prop + ': ' + val);
    }
  }
  assert.deepEqual(bad, []);
  for (const p of ['#fff', '1px solid #abcdef', 'rgb(0, 0, 0)', 'oklch(0.5 0.1 20)', 'red', '2px dashed gold', 'color-mix(in srgb, var(--ink) 50%, white)']) assert.ok(rawColour(p), p);
  for (const p of ['var(--ink)', '1px solid var(--rule)', 'var(--lr-craft-fill)', 'transparent', '"red"', 'none', '12px/1.5 var(--f-data)', 'Big Shoulders Display', 'linear-gradient(var(--hi), var(--hi))']) assert.ok(!rawColour(p), p);
});

