// the px figure of a declaration in the rules of a selector: min-height or height, in the base rule or the phone block
const px = (sel, prop) => { const out = []; for (const r of rules) if (r.sel.split(/\s*,\s*/).includes(sel)) { const m = new RegExp('(?:^|[;\\s])' + prop + ':\\s*(\\d+)px').exec(r.body); if (m) out.push(+m[1]); } return out; };
test('the phone: the rail is a bar fixed to the bottom, the switcher gives way, no sideways scroll rule broken, 40 px tap targets on every button, tab, select, field and tick', () => {
  assert.match(body, /@media \(max-width: 700px\)/);
  assert.ok(/@media \(max-width: 700px\)\s*\{[^@]*\.lists-page \.switcher \{ display: none; \}/.test(body), 'the switcher is hidden on a phone, as in Submersibles');
  assert.ok(/\.lists-tabs \{ position: fixed;[^}]*bottom: 0;[^}]*height: 64px;/.test(body), 'a 64 px bar fixed to the bottom');
  for (const [sel, min] of [['.ltab', 40], ['.sec-toggle', 40], ['.icon-b', 40], ['.lsheet .lx', 36], ['.lsheet .lfield input', 40], ['.lbtn-o', 40], ['.lists-bar .btn', 40], ['.lines .btn', 40], ['.lists-panel .btn', 40], ['.tick', 40], ['.lists-steps .step-tab', 40]]) {
    const all = px(sel, 'min-height').concat(px(sel, 'height')); assert.ok(all.some((v) => v >= min), sel + ' is at least ' + min + ' px');
  }
  assert.ok(px('.lsheet .sfoot .lbtn-p', 'min-height').some((v) => v >= 48), 'a sheet\'s main action is 48 px high on a phone');
  assert.ok(rules.some((r) => /\.lists-form input/.test(r.sel) && /min-height:\s*40px/.test(r.body)), 'fields');
  assert.ok(!/min-width:\s*(3|4|5|6|7|8|9)\d\dpx/.test(body.replace(/minmax\([^)]*\)/g, '')), 'no fixed minimum width of 300 px or more');
  assert.ok(!/clip-path[^;]*;[^}]*:focus/.test(body) && !rules.some((r) => /clip-path/.test(r.body) && /(button|input|select|\.lk|\.ltab|\.sec-toggle|\.icon-b|\.lbtn)/.test(r.sel)), 'no clip-path on anything that takes focus');
});

